async function loadPagePanel(url, pushState = true) {
  const page = document.querySelector("main");
  if (!page) {
    window.location.href = url.href;
    return;
  }

  document.body.classList.add("page-panel-loading");

  try {
    const response = await fetch(url.href, { headers: { "X-Requested-With": "page-panel" } });
    if (!response.ok) throw new Error(`Page returned ${response.status}`);

    const html = await response.text();
    const nextDocument = new DOMParser().parseFromString(html, "text/html");
    const nextMain = nextDocument.querySelector("main");
    const nextFooter = nextDocument.querySelector("footer.site-footer");
    const currentFooter = document.querySelector("footer.site-footer");

    if (!nextMain) throw new Error("Page content missing");

    page.replaceWith(nextMain);
    if (nextFooter && currentFooter) {
      currentFooter.replaceWith(nextFooter);
    }

    document.title = nextDocument.title;
    document.body.className = nextDocument.body.className;
    updateActiveNav(url.pathname);
    enhancePage();
    window.__pagePanelNavigations = (window.__pagePanelNavigations || 0) + 1;
    document.documentElement.dataset.panelNavigations = String(window.__pagePanelNavigations);
    window.scrollTo(0, 0);

    if (pushState) {
      history.pushState({ page: url.href }, "", url.href);
    }
  } catch (error) {
    window.location.href = url.href;
  } finally {
    document.body.classList.remove("page-panel-loading");
  }
}

document.addEventListener("click", (event) => {
  const target = event.target;
  const link = target?.closest ? target.closest("a") : target?.parentElement?.closest("a");
  if (!link) return;
  if (link.dataset.panelLink === "true") return;
  if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
  if (link.target && link.target !== "_self") return;
  if (link.origin !== window.location.origin) return;

  const url = new URL(link.href, window.location.href);
  const isSameOrigin = url.origin === window.location.origin;
  const isHtmlPage = url.pathname.endsWith(".html") || url.pathname.endsWith("/");

  if (!isSameOrigin || !isHtmlPage) return;

  event.preventDefault();
  loadPagePanel(url);
}, true);

window.addEventListener("popstate", () => {
  loadPagePanel(new URL(window.location.href), false);
});

