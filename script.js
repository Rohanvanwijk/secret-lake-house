let facebookResizeObserver;
function initFacebookFeeds() {
  facebookResizeObserver?.disconnect();
  document.querySelectorAll('.video-grid .facebook-video-card iframe').forEach(frame => {
    if (frame.parentElement.classList.contains("facebook-feed-crop")) return;
    const viewport = document.createElement("div");
    viewport.className = "facebook-feed-crop";
    frame.before(viewport);
    viewport.append(frame);
  });
  facebookResizeObserver = new ResizeObserver(entries => {
    entries.forEach(({ target, contentRect }) => {
      const frame = target.querySelector('iframe[src*="facebook.com/plugins/page.php"]');
      if (!frame) return;
      const width = Math.max(180, Math.min(500, Math.floor(contentRect.width)));
      if (frame.dataset.feedWidth === String(width)) return;
      frame.dataset.feedWidth = String(width);
      const url = new URL(frame.src);
      const cropped = target.classList.contains("facebook-feed-crop");
      const height = cropped ? 434 : 520;
      url.searchParams.set("href", "https://www.facebook.com/secretlakehousekampot");
      url.searchParams.set("width", String(width));
      url.searchParams.set("height", String(height));
      if (cropped) {
        url.searchParams.set("small_header", "true");
        url.searchParams.set("hide_cover", "true");
      }
      url.searchParams.delete("appId");
      frame.src = url.href;
      frame.style.width = width + "px";
      frame.style.maxWidth = "100%";
      frame.style.height = height + "px";
      frame.style.minHeight = height + "px";
      frame.style.flex = "0 0 " + height + "px";
      frame.style.marginInline = "auto";
      frame.style.aspectRatio = "auto";
    });
  });
  document.querySelectorAll('iframe[src*="facebook.com/plugins/page.php"]').forEach(frame => facebookResizeObserver.observe(frame.parentElement));
}

