      head.className = "robot-head";
      head.append(mascot.querySelector("img").cloneNode(true));
      mascot.querySelectorAll(".robot-eyelid").forEach(eye => head.append(eye));
      const smile = document.createElement("span");
      smile.className = "robot-smile";
      head.append(smile);
