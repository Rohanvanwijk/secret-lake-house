function seasonFromMonthDay(month, day) {
  if (month === 12 && day >= 20) return "peak";
  if (month === 1 && day <= 4) return "peak";
  if (month > 10 || month < 4) return "high";
  if (month === 10 && day >= 15) return "high";
  return "low";
}

function extractMonthDay(question) {
  const cleanQuestion = normalizeBotText(question);
  for (const [name, month] of Object.entries(botMonths)) {
    let match = cleanQuestion.match(new RegExp(`\\b${name}\\s+(\\d{1,2})(?:st|nd|rd|th)?\\b`));
    if (match) return { month, day: Number(match[1]) };
    match = cleanQuestion.match(new RegExp(`\\b(\\d{1,2})(?:st|nd|rd|th)?\\s+${name}\\b`));
    if (match) return { month, day: Number(match[1]) };
  }

  const numeric = cleanQuestion.match(/\b(\d{1,2})[/-](\d{1,2})(?:[/-]\d{2,4})?\b/);
  if (numeric) {
    const first = Number(numeric[1]);
    const second = Number(numeric[2]);
    return first > 12 ? { month: second, day: first } : { month: first, day: second };
  }

  return null;
}

function detectRateSeason(question) {
  const cleanQuestion = normalizeBotText(question);
  if (["peak", "festival", "khmer new year", "chinese new year", "pchumben", "pchum ben", "water festival"].some((word) => cleanQuestion.includes(word))) return "peak";
  if (cleanQuestion.includes("high season")) return "high";
  if (cleanQuestion.includes("low season")) return "low";

  const now = new Date();
  if (cleanQuestion.includes("today")) return seasonFromMonthDay(now.getMonth() + 1, now.getDate());
  if (cleanQuestion.includes("tomorrow")) {
    const tomorrow = new Date(now);
    tomorrow.setDate(now.getDate() + 1);
    return seasonFromMonthDay(tomorrow.getMonth() + 1, tomorrow.getDate());
  }

  const monthDay = extractMonthDay(question);
  if (monthDay) return seasonFromMonthDay(monthDay.month, monthDay.day);
  return "all";
}

