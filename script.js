    const resetFace = () => {
      cancelAnimationFrame(faceFrame);
      mascot?.style.setProperty("--face-x", "0px");
      mascot?.style.setProperty("--face-y", "0px");
      mascot?.style.setProperty("--face-turn", "0deg");
    };
    document.addEventListener("pointermove", event => {
      if (!mascot?.isConnected || event.pointerType === "touch" || reducedMotion.matches || bot.classList.contains("hidden")) return;
      cancelAnimationFrame(faceFrame);
      faceFrame = requestAnimationFrame(() => {
        const rect = mascot.getBoundingClientRect();
        const x = Math.max(-1, Math.min(1, (event.clientX - rect.left - rect.width / 2) / 300));
        mascot.style.setProperty("--face-x", x * 1.5 + "px");
        mascot.style.setProperty("--face-y", "0px");
        mascot.style.setProperty("--face-turn", "0deg");
      });
    });
    document.documentElement.addEventListener("pointerleave", resetFace);
