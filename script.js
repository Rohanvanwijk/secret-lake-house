function getBotReply(question) {
  const mapReply = getMapReply(question);
  if (mapReply) return mapReply;
  const cleanQuestion = normalizeBotText(question);
  const conversationReply = getConversationReply(question);
  if (conversationReply) {
    return {
      answer: conversationReply,
      needs_follow_up: false
    };
  }

  const farewellWords = ["bye", "goodbye", "see you", "see you soon", "good night"];
  const farewell = farewellWords.some((word) => new RegExp(`\\b${word}\\b`).test(cleanQuestion));

  if (farewell) {
    return {
      answer: "Goodbye, and thank you for contacting Secret Lake House. We hope to welcome you by the lake soon.",
      needs_follow_up: false
    };
  }

  if (looksLikeStayDateReply(question)) {
    return {
      answer: getRoomRateAnswer(question),
      needs_follow_up: false
    };
  }

  const match = botAnswers
    .map((item) => ({ item, score: scoreBotAnswer(question, item) }))
    .sort((a, b) => b.score - a.score)[0];

  if (match?.score > 0) {
    return {
      answer: match.item.type === "roomRates" ? getRoomRateAnswer(question) : match.item.answer,
      needs_follow_up: false
    };
  }

  return {
    answer: "I may not know that yet, but I can still help with rooms, prices, food and drinks, dining huts, pool visits, opening hours, directions, bookings, children, and special occasions. You can ask me in a simple way, like: room price, menu, location, or opening hours.",
    needs_follow_up: false
  };
}

async function getSmartBotReply(question) {
  const mapReply = getMapReply(question);
  if (mapReply) return mapReply;
  try {
    const response = await fetch("/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message: question })
    });
    if (!response.ok) throw new Error(`Chat endpoint returned ${response.status}`);
    return await response.json();
  } catch {
    return getBotReply(question);
  }
}

