function initBookingWidgets() {
  document.querySelectorAll("[data-widget]").forEach((widget) => {
    if (widget.dataset.ready === "true") return;
    widget.dataset.ready = "true";

    const buttons = widget.querySelectorAll("[data-mode]");
    const labelOne = widget.querySelector("[data-label-one]");
    const labelTwo = widget.querySelector("[data-label-two]");
    const labelThree = widget.querySelector("[data-label-three]");
    const select = widget.querySelector("[data-select]");
    const action = widget.querySelector("[data-action]");
    const fieldOne = widget.querySelector("[data-field-one]");
    const fieldTwo = widget.querySelector("[data-field-two]");
    const requestType = widget.querySelector("[data-request-type]");
    const submitsEmail = widget.dataset.submitEmail === "true";

    buttons.forEach((button) => {
      button.addEventListener("click", () => {
        buttons.forEach((item) => item.classList.remove("active"));
        button.classList.add("active");

        const dine = button.dataset.mode === "dine";
        labelOne.textContent = dine ? "Date" : "Check-in";
        labelTwo.textContent = dine ? "Time" : "Check-out";
        labelThree.textContent = dine ? "Hut or table preference" : "Room type";
        if (fieldOne) {
          fieldOne.type = "date";
          fieldOne.name = dine ? "dining_date" : "check_in";
        }
        if (fieldTwo) {
          fieldTwo.type = dine ? "time" : "date";
          fieldTwo.name = dine ? "dining_time" : "check_out";
        }
        if (requestType) {
          requestType.value = dine ? "Dining hut or table request" : "Stay booking request";
        }
        if (select) {
          select.name = dine ? "hut_or_table_preference" : "room_type";
        }
        select.innerHTML = dine
          ? "<option>Poolside Restaurant Table</option><option>Overwater Wooden Hut</option><option>Bamboo Hut</option><option>Lake View Table</option>"
          : "<option>Khmer House - Suite Room</option><option>Khmer House - Twin Deluxe Room</option><option>Bungalow - Family Room</option><option>Family Studio Room</option>";
        action.textContent = dine ? "Reserve Dining Hut" : "Check Availability";
      });
    });

    if (!submitsEmail) {
      action.addEventListener("click", () => {
        window.location.href = "https://t.me/secretlakehousekampot";
      });
    }
  });
}

